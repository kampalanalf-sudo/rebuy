#!/usr/bin/env python3
"""Bundle every Rebuy source file into the JSON shape the Vercel
`create_deployment` API expects:

    {"files": [{"file": "app/db.py", "data": "<base64 of the file>"}, ...]}

Usage
-----
    python3 scripts/build_payload.py                       # full bundle -> /tmp/rebuy_payload.json
    python3 scripts/build_payload.py --vercel              # lean bundle (pre-gzipped static pages)
    python3 scripts/build_payload.py --vercel --split 88   # chunk so no request body exceeds ~88 KB
    python3 scripts/build_payload.py --vercel --vault data/rebuy.db --vercel-vault
                                                          # also ship the demo database as a
                                                          # lazily-restored snapshot

The `--vault` option appends `scripts/restore_vault.py`, which carries the SQLite
file as a zlib+base64 constant and writes it to disk when the platform starts,
so a serverless deployment can serve the full 120-shop demo without a database
service. Restore is only attempted on demand (see api/index.py).
"""
from __future__ import annotations

import argparse
import base64
import json
import os
import sys
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INCLUDE_DIRS = ("app", "static", "api")
INCLUDE_FILES = ("serve.py", "vercel.json", "requirements.txt", "README.md", ".vercelignore")
SKIP_DIRS = {"__pycache__", ".git", "data", "node_modules", ".vercel"}
SKIP_EXT = (".pyc", ".pyo", ".db", ".db-wal", ".db-shm")

RESTORE_TEMPLATE = '''#!/usr/bin/env python3
"""Restore the bundled Rebuy SQLite snapshot.

Generated by scripts/build_payload.py --vault. The database is stored below as a
zlib-compressed, base64-encoded constant; restore() writes it to REBUY_DB
(default /tmp/rebuy.db on Vercel). Called automatically by api/index.py when the
database file is missing.
"""
import base64
import os
import zlib

BLOB = (
{chunks}
)


def restore(path: str | None = None, force: bool = False) -> str:
    path = path or os.environ.get("REBUY_DB") or "data/{basename}"
    if os.path.exists(path) and not force:
        return path
    os.makedirs(os.path.dirname(os.path.abspath(path)) or ".", exist_ok=True)
    raw = zlib.decompress(base64.b64decode(BLOB))
    tmp = path + ".tmp"
    with open(tmp, "wb") as fh:
        fh.write(raw)
    os.replace(tmp, path)
    print(f"[rebuy] restored {{len(raw)/1048576:.1f}} MB snapshot -> {{path}}")
    return path


if __name__ == "__main__":
    restore(force=True)
'''


def collect(vercel: bool = False) -> list[dict]:
    files: list[dict] = []
    for directory in INCLUDE_DIRS:
        base = os.path.join(ROOT, directory)
        for dirpath, dirnames, filenames in os.walk(base):
            dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
            for name in sorted(filenames):
                if name.endswith(SKIP_EXT):
                    continue
                if vercel and name.endswith((".html", ".css", ".js")) and not name.endswith(".gz"):
                    continue  # the .gz twin ships instead
                full = os.path.join(dirpath, name)
                rel = os.path.relpath(full, ROOT).replace(os.sep, "/")
                with open(full, "rb") as fh:
                    files.append({"file": rel, "data": base64.b64encode(fh.read()).decode()})
    for name in INCLUDE_FILES:
        full = os.path.join(ROOT, name)
        if os.path.isfile(full):
            with open(full, "rb") as fh:
                files.append({"file": name, "data": base64.b64encode(fh.read()).decode()})
    return files


def vault_file(sqlite_path: str, vercel: bool) -> dict:
    with open(sqlite_path, "rb") as fh:
        raw = fh.read()
    blob = base64.b64encode(zlib.compress(raw, 9)).decode()
    chunks = "\n".join('    "' + blob[i:i + 96] + '"' for i in range(0, len(blob), 96))
    source = RESTORE_TEMPLATE.format(chunks=chunks, basename=os.path.basename(sqlite_path))
    print(f"vault: {sqlite_path} ({len(raw)/1048576:.1f} MB) -> {len(blob)/1024:.0f} KB base64")
    return {"file": "scripts/restore_vault.py",
            "data": base64.b64encode(source.encode()).decode()}


def write_chunks(files: list[dict], out_path: str, limit: int) -> None:
    chunks, current, size = [], [], 0
    for item in files:
        item_size = len(json.dumps(item))
        if current and size + item_size > limit:
            chunks.append(current)
            current, size = [], 0
        current.append(item)
        size += item_size
    if current:
        chunks.append(current)
    stem = os.path.splitext(out_path)[0]
    for index, chunk in enumerate(chunks, 1):
        payload = {"name": "rebuy", "files": chunk}
        path = f"{stem}.part{index:02d}.json"
        with open(path, "w") as fh:
            json.dump(payload, fh)
        print(f"  {path}: {len(chunk)} files, {len(json.dumps(payload))/1024:.0f} KB")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default="/tmp/rebuy_payload.json")
    parser.add_argument("--split", type=int, default=0, help="also write chunk files of at most N bytes of JSON")
    parser.add_argument("--vercel", action="store_true", help="lean bundle for the Vercel API")
    parser.add_argument("--vault", default="", help="SQLite file to bundle as a restorable snapshot")
    args = parser.parse_args()

    files = collect(args.vercel)
    if args.vault:
        files.append(vault_file(args.vault, args.vercel))
    payload = {"name": "rebuy", "files": files}
    with open(args.out, "w") as fh:
        json.dump(payload, fh)
    total_kb = sum(len(f["data"]) for f in files) / 1024
    print(f"wrote {args.out}: {len(files)} files, {total_kb:.0f} KB of base64")
    if args.split:
        write_chunks(files, args.out, args.split)
    return 0


if __name__ == "__main__":
    sys.exit(main())
